#!/bin/bash
# Deploy (or update) the instant Junk cleaner on Cloudflare Workers.
#
#   worker/deploy.sh example.com   first time: sets it up on a hidden URL under h.example.com
#   worker/deploy.sh               after editing rules.toml: upload the rules and code again
#   worker/deploy.sh --login       copy the Mac's sign-in to the Worker again (after --login on the Mac)
#
# Needs: a domain on Cloudflare, `npx wrangler login` done once, and ./setup.sh done.
set -euo pipefail
cd "$(dirname "$0")"
W="npx --yes wrangler@4.154.0"
PY=../.venv/bin/python

if [ ! -f wrangler.toml ]; then
  domain="${1:?First time: worker/deploy.sh yourdomain.com  (a domain on your Cloudflare account)}"
  echo "Creating the KV namespace ..."
  kv_id=$($W kv namespace create junk-cleaner-state | grep -oE '[0-9a-f]{32}' | head -1)
  [ -n "$kv_id" ] || { echo "Could not create the KV namespace." >&2; exit 1; }
  # Its own subdomain (a site on the domain itself would take priority over a route),
  # and a random path, linked from nowhere; every other path answers "Not found".
  hook="https://h.$domain/$(openssl rand -hex 16)"
  client_id=$($PY -c 'import tomllib; print(tomllib.load(open("../rules.toml","rb"))["client_id"])')
  cat > wrangler.toml <<EOF
# Generated by deploy.sh. Personal (your domain and hidden URL): not in git.
name = "junk-cleaner"
main = "worker.mjs"
compatibility_date = "2025-09-01"
workers_dev = false
preview_urls = false
routes = [{ pattern = "h.$domain", custom_domain = true }]
kv_namespaces = [{ binding = "STATE", id = "$kv_id" }]

[triggers]
crons = ["*/15 * * * *"]

[vars]
CLIENT_ID = "$client_id"
HOOK_URL = "$hook"

[observability]
enabled = true
EOF
fi
hook=$(grep '^HOOK_URL' wrangler.toml | cut -d'"' -f2)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

if [ "${1:-}" = "--login" ] || ! $W kv key list --binding STATE --remote | grep -q '"refresh_token"'; then
  $PY prepare.py token "$tmp/token"
  $W kv key put refresh_token --path "$tmp/token" --binding STATE --remote
  $W kv key delete access_token --binding STATE --remote >/dev/null 2>&1 || true
fi

echo "Uploading rules ..."
$PY prepare.py rules "$tmp/rules.json"
$W kv key put rules --path "$tmp/rules.json" --binding STATE --remote

$W deploy
sleep 5
curl -fsS "$hook?kick" >/dev/null && echo "Deployed. Subscription and first sweep started; logs: Cloudflare dashboard → Workers → junk-cleaner → Logs"
